package com.velvet.app.recommendation.identity

import com.velvet.app.data.Song
import com.velvet.app.playback.SongIdentity
import com.velvet.app.recommendation.model.ReleaseAudioClass
import com.velvet.app.recommendation.model.ReleaseClassification
import com.velvet.app.recommendation.model.VersionKind
import java.util.Locale

/**
 * Pure Kotlin strict Original Studio Music Audio classifier.
 *
 * Non-negotiable policy:
 * - Official music videos, lyric videos, visualizers, live concerts, UGC/fan uploads,
 *   and alternates (remix/cover/mashup/slowed/reverb) are strictly rejected.
 * - Verified channel or known label upload alone NEVER implies studio audio.
 * - Candidates without positive studio/Topic audio evidence resolve fail-closed to [ReleaseAudioClass.UNVERIFIED].
 */
object ReleaseAudioClassifier {

    private val NON_MUSIC_SPOKEN_REGEX = Regex(
        """(?i)\b(full movie|film scene|movie scene|trailer|teaser|podcast|episode|interview|documentary|""" +
            """audiobook|vlog|funny moments|roast|unboxing|talk show|behind the scenes|making of|bloopers|""" +
            """whatsapp status|status video|reels?|tiktok|dialogue|dialogues|parody|amv)\b""",
    )

    private val LYRIC_VIDEO_REGEX = Regex(
        """(?i)(?:\b(?:lyric video|lyrical video|lyrics video|lyrical song|with lyrics|full lyrics|lyrics on screen)\b|[\[(]\s*lyrics?\s*[\])]|-\s*lyrics\b|\blyrics\s*$)""",
    )

    private val VISUALIZER_REGEX = Regex(
        """(?i)\b(visualizer|official visualizer|animated video|animated music video|motion poster|motion art|canvas video|3d animation video)\b""",
    )

    private val OFFICIAL_VIDEO_REGEX = Regex(
        """(?i)(?:\b(?:official music video|official video song|official video|music video|full video song|full video|""" +
            """video song|4k video|hd video|official mv|dance video|hook step video|promotional video|promo video)\b|[\[(]\s*mv\s*[\])]|-\s*mv\b)""",
    )

    private val LIVE_CONCERT_REGEX = Regex(
        """(?i)(?:\b(?:live performance|live concert|live session|in concert|stage performance|mtv unplugged|""" +
            """unplugged live|live version|live at|live from)\b|[\[(]\s*live\s*[\])]|-\s*live\b)""",
    )

    private val COVER_OR_UGC_REGEX = Regex(
        """(?i)\b(fan made|fan video|fan edit|cover by|acoustic cover|guitar cover|piano cover|drum cover|""" +
            """vocal cover|cover song|karaoke|8d audio|16d audio|bass boosted|reaction|tribute video|reupload|re-upload)\b""",
    )

    private val ALTERNATE_VERSION_REGEX = Regex(
        """(?i)(?:\b(?:remix|remixed|dj mix|club mix|slowed|reverb|sped up|speed up|speedup|nightcore|""" +
            """lofi|lo-fi|mashup|reprise|jhankar(?:\s+beat)?|unplugged|acoustic version|instrumental version|instrumental)\b|[\[(]\s*acoustic\s*[\])]|-\s*acoustic\b)""",
    )

    private val EXPLICIT_STUDIO_AUDIO_REGEX = Regex(
        """(?i)(?:\b(?:official audio|original audio|full audio|audio song|audio track|studio audio|studio version)\b|[\[(]\s*(?:official\s+)?audio\s*[\])]|-\s*audio\b)""",
    )

    private val EXPLICIT_OST_AUDIO_REGEX = Regex(
        """(?i)\b(original motion picture soundtrack|original soundtrack|official ost|ost audio)\b""",
    )

    private val DISTRIBUTOR_DESCRIPTION_REGEX = Regex(
        """(?i)\b(provided to youtube by|auto-generated by youtube)\b""",
    )

    fun detectVersionKind(song: Song): VersionKind {
        val title = song.title
        val lower = title.lowercase(Locale.ROOT)
        return when {
            OFFICIAL_VIDEO_REGEX.containsMatchIn(lower) -> VersionKind.OFFICIAL_MUSIC_VIDEO
            LYRIC_VIDEO_REGEX.containsMatchIn(lower) -> VersionKind.LYRIC_VIDEO
            VISUALIZER_REGEX.containsMatchIn(lower) -> VersionKind.VISUALIZER
            LIVE_CONCERT_REGEX.containsMatchIn(lower) -> VersionKind.LIVE
            COVER_OR_UGC_REGEX.containsMatchIn(lower) -> {
                if (lower.contains("karaoke")) VersionKind.KARAOKE else VersionKind.COVER
            }
            lower.contains("slowed") -> VersionKind.SLOWED
            lower.contains("reverb") -> VersionKind.SLOWED
            lower.contains("sped up") || lower.contains("speed up") || lower.contains("speedup") || lower.contains("nightcore") ->
                VersionKind.SPED_UP
            lower.contains("mashup") -> VersionKind.MASHUP
            lower.contains("remix") || lower.contains("dj mix") || lower.contains("club mix") -> VersionKind.REMIX
            lower.contains("unplugged") -> VersionKind.UNPLUGGED
            lower.contains("acoustic") -> VersionKind.ACOUSTIC
            lower.contains("instrumental") -> VersionKind.INSTRUMENTAL
            lower.contains("reprise") -> VersionKind.REPRISE
            lower.contains("remaster") -> VersionKind.REMASTER
            else -> {
                val cls = classify(song)
                if (cls.isVerifiedOriginalAudio) VersionKind.ORIGINAL_STUDIO else VersionKind.UNKNOWN
            }
        }
    }

    fun classify(song: Song): ReleaseClassification {
        val title = song.title.trim()
        val rawUploader = (song.rawUploaderName ?: song.artist).trim()
        val combinedText = "$title $rawUploader ${song.releaseDescriptionHint.orEmpty()}"
        val evidence = mutableSetOf<String>()

        if (song.isTopicRelease) evidence.add("topic_release_flag")
        if (song.isUploaderVerified) evidence.add("verified_channel")
        if (song.hasSquareArtwork) evidence.add("square_artwork_hint")
        if (!song.releaseDescriptionHint.isNullOrBlank()) evidence.add("release_description_hint")
        if (song.preferredMusicSource) evidence.add("legacy_preferred_music_source")

        // 1. Strict hard rejections BEFORE checking verified/Topic attributes:
        if (NON_MUSIC_SPOKEN_REGEX.containsMatchIn(combinedText)) {
            evidence.add("non_music_keyword")
            return ReleaseClassification(
                audioClass = ReleaseAudioClass.REJECTED_NON_MUSIC,
                confidence = 0.95,
                evidence = evidence,
                reasonCode = "rejected_non_music_content",
            )
        }
        if (LYRIC_VIDEO_REGEX.containsMatchIn(title) || LYRIC_VIDEO_REGEX.containsMatchIn(rawUploader)) {
            evidence.add("lyric_video_marker")
            return ReleaseClassification(
                audioClass = ReleaseAudioClass.REJECTED_LYRIC_VIDEO,
                confidence = 0.95,
                evidence = evidence,
                reasonCode = "rejected_lyric_video",
            )
        }
        if (VISUALIZER_REGEX.containsMatchIn(title) || VISUALIZER_REGEX.containsMatchIn(rawUploader)) {
            evidence.add("visualizer_marker")
            return ReleaseClassification(
                audioClass = ReleaseAudioClass.REJECTED_VISUALIZER,
                confidence = 0.95,
                evidence = evidence,
                reasonCode = "rejected_visualizer",
            )
        }
        if (OFFICIAL_VIDEO_REGEX.containsMatchIn(title)) {
            evidence.add("official_video_marker")
            return ReleaseClassification(
                audioClass = ReleaseAudioClass.REJECTED_OFFICIAL_VIDEO,
                confidence = 0.96,
                evidence = evidence,
                reasonCode = "rejected_official_music_video",
            )
        }
        if (LIVE_CONCERT_REGEX.containsMatchIn(title) || LIVE_CONCERT_REGEX.containsMatchIn(rawUploader)) {
            evidence.add("live_performance_marker")
            return ReleaseClassification(
                audioClass = ReleaseAudioClass.REJECTED_LIVE,
                confidence = 0.94,
                evidence = evidence,
                reasonCode = "rejected_live_recording",
            )
        }
        if (COVER_OR_UGC_REGEX.containsMatchIn(combinedText)) {
            evidence.add("cover_or_ugc_marker")
            return ReleaseClassification(
                audioClass = ReleaseAudioClass.REJECTED_COVER_OR_UGC,
                confidence = 0.92,
                evidence = evidence,
                reasonCode = "rejected_cover_or_ugc",
            )
        }
        if (ALTERNATE_VERSION_REGEX.containsMatchIn(title)) {
            evidence.add("alternate_version_marker")
            return ReleaseClassification(
                audioClass = ReleaseAudioClass.REJECTED_ALTERNATE_VERSION,
                confidence = 0.92,
                evidence = evidence,
                reasonCode = "rejected_alternate_version",
            )
        }

        // Bracketed or suffix video indicators e.g. "(Video)", "[HD Video]", "- Video" (without false-triggering song titles like "Video Games")
        val titleLow = title.lowercase(Locale.ROOT)
        if (Regex("""(?i)(?:[\[(][^)\]]*\bvideo\b[^)\]]*[\])]|-\s*(?:\w+\s+)?video\b|\bvideo\s+(?:version|edit|cut)\b)""")
                .containsMatchIn(titleLow)
        ) {
            evidence.add("video_release_marker")
            return ReleaseClassification(
                audioClass = ReleaseAudioClass.REJECTED_OFFICIAL_VIDEO,
                confidence = 0.88,
                evidence = evidence,
                reasonCode = "rejected_video_release",
            )
        }

        // 2. Positive Original Studio Audio Verification (strict, never trusting verified channel alone):
        val rawEndsTopic = rawUploader.endsWith("- Topic", ignoreCase = true) ||
            song.artist.trim().endsWith("- Topic", ignoreCase = true) ||
            song.artistUrl?.contains("- Topic", ignoreCase = true) == true
        val hasDistributorDesc = song.releaseDescriptionHint?.let { DISTRIBUTOR_DESCRIPTION_REGEX.containsMatchIn(it) } == true ||
            DISTRIBUTOR_DESCRIPTION_REGEX.containsMatchIn(title)

        if (song.isTopicRelease || rawEndsTopic || hasDistributorDesc) {
            if (rawEndsTopic) evidence.add("topic_channel_suffix")
            if (hasDistributorDesc) evidence.add("distributor_auto_generated_desc")
            val conf = if (song.isTopicRelease || rawEndsTopic || hasDistributorDesc) 0.95 else 0.88
            return ReleaseClassification(
                audioClass = ReleaseAudioClass.VERIFIED_TOPIC_AUDIO,
                confidence = conf,
                evidence = evidence,
                reasonCode = "verified_topic_audio",
            )
        }

        val normUploaderLow = rawUploader.lowercase(Locale.ROOT)
        val isKnownLabel = SongIdentity.RECORD_LABELS.any { label -> normUploaderLow.contains(label) }
        val isVerifiedOrKnownRightsHolder = song.isUploaderVerified || isKnownLabel
        if (isKnownLabel) evidence.add("known_record_label")

        val hasExplicitOstMarker = EXPLICIT_OST_AUDIO_REGEX.containsMatchIn(title) ||
            (song.releaseDescriptionHint?.let { EXPLICIT_OST_AUDIO_REGEX.containsMatchIn(it) } == true)
        if (hasExplicitOstMarker && isVerifiedOrKnownRightsHolder) {
            evidence.add("explicit_ost_marker")
            return ReleaseClassification(
                audioClass = ReleaseAudioClass.VERIFIED_OST_AUDIO,
                confidence = 0.86,
                evidence = evidence,
                reasonCode = "verified_ost_audio",
            )
        }

        val hasExplicitAudioMarker = EXPLICIT_STUDIO_AUDIO_REGEX.containsMatchIn(title) ||
            (song.releaseDescriptionHint?.let { EXPLICIT_STUDIO_AUDIO_REGEX.containsMatchIn(it) } == true)
        if (hasExplicitAudioMarker && isVerifiedOrKnownRightsHolder) {
            evidence.add("explicit_audio_marker")
            val audioClass = if (isKnownLabel) {
                ReleaseAudioClass.VERIFIED_LABEL_STUDIO_AUDIO
            } else {
                ReleaseAudioClass.VERIFIED_STUDIO_AUDIO
            }
            return ReleaseClassification(
                audioClass = audioClass,
                confidence = 0.85,
                evidence = evidence,
                reasonCode = if (isKnownLabel) "verified_label_studio_audio" else "verified_official_audio",
            )
        }

        // 3. Fail-closed: verified uploaders, known labels, or legacy preferredMusicSource
        // WITHOUT explicit Topic or explicit Audio evidence resolve to UNVERIFIED.
        val reason = when {
            hasExplicitAudioMarker -> "audio_marker_on_unverified_channel"
            song.isUploaderVerified || isKnownLabel -> "verified_channel_missing_audio_proof"
            song.preferredMusicSource -> "legacy_preferred_source_ambiguous"
            else -> "insufficient_release_audio_metadata"
        }
        return ReleaseClassification(
            audioClass = ReleaseAudioClass.UNVERIFIED,
            confidence = if (song.isUploaderVerified) 0.40 else 0.25,
            evidence = evidence,
            reasonCode = reason,
        )
    }
}
